import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const checks = [];
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) });
const routes = read('backend/routes/marketplaceFulfilmentRoutes.js');
const fulfilment = read('backend/services/marketplaceFulfilment.service.js');
const escrow = read('backend/services/escrow.service.js');
const paymentCallback = read('backend/services/paymentCallback.service.js');
const paymentAtomic = read('backend/utils/atomicTransactions.js');
const leadService = read('backend/services/leadService.js');
const offerController = read('backend/controllers/conversionFunnelController.js');
const offerRoutes = read('backend/routes/leadRoutes.js');
const offerService = read('backend/services/offerNegotiation.service.js');
const offerControllerApi = read('backend/controllers/offerNegotiationController.js');
const offerMigration = read('supabase/migrations/20261110120000_canonical_offer_negotiation_workflow.sql');
const offerClient = read('src/services/leadApi.ts');
const inspection = read('backend/inspection/services/bookingService.js');
const dispute = read('backend/services/dispute.service.js');
const disputeRoutes = read('backend/routes/disputeRoutes.js');
const refund = read('backend/controllers/escrowController.js');

check('Purchase fulfilment routes require authenticated actor', routes.includes('router.use') || routes.includes('protect'));
check('Collection and transfer actions are protected and CSRF-guarded', routes.includes('csrfProtection') && routes.includes('markCollection') && routes.includes('markTransfer'));
check('Purchase dispute action is exposed through canonical outcome route', routes.includes('openPurchaseDispute'));
check('Buyer/seller party authorization is enforced', fulfilment.includes('assertParty') && fulfilment.includes('assertSeller'));
check('Ownership transfer requires completed vehicle collection', fulfilment.includes("outcome.collection_status!=='collected'"));
const releasedStart = fulfilment.indexOf('if(escrowStatus === "released")');
const releasedBranch = fulfilment.slice(releasedStart);
check('Car sold write failure is no longer swallowed', !/update\("cars", outcome\.car_id[\s\S]{0,220}\.catch\(/.test(fulfilment));
check('Escrow financial release is delegated to atomic state transition', escrow.includes('atomicTransitionEscrow') && escrow.includes('STATES.RELEASED'));
check('Escrow release/refund/dispute outcome-sync failures propagate to caller', !/syncPurchaseOutcomeFromEscrow\([\s\S]{0,180}\)\.catch\(/.test(escrow));
check('Refund-completion controller does not hide purchase-outcome sync failure', refund.includes('await syncPurchaseOutcomeFromEscrow(req.params.id, "refunded", { actorId: req.user.id, reason: "Escrow refund completed" });'));
check('Purchase callback settles through canonical atomic RPC', paymentCallback.includes('atomicSettlePurchasePayment') && paymentAtomic.includes('kayad_settle_purchase_payment_atomic'));
check('Lead creation uses atomic create-or-resolve RPC', leadService.includes('kayad_create_lead_atomic'));
check('Inspection booking has canonical booking service', inspection.includes('booking') || inspection.includes('create'));
check('Dispute route and service are present', disputeRoutes.includes('dispute') && dispute.includes('atomic') );
check('Refund completion uses escrow-scoped refund record and atomic RPC', refund.includes('kayad_complete_escrow_refund_atomic') && refund.includes('refundRow.escrow_id'));
check('Legacy offer event remains analytics-only and is not mistaken for negotiation', offerController.includes('ConversionFunnel'));
check('Canonical offer routes expose participant-scoped read, submit and response actions', offerRoutes.includes('/:leadId/offers') && offerRoutes.includes('/:leadId/offers/:offerId/actions'));
check('Offer controller authorizes buyer and seller against canonical lead', offerControllerApi.includes('participant(lead, req.user?.id)'));
check('Offer service delegates mutations to atomic database RPC', offerService.includes('kayad_offer_action'));
check('Offer schema persists counteroffers, decisions, expiry and immutable events', offerMigration.includes('marketplace_offers') && offerMigration.includes('marketplace_offer_events') && offerMigration.includes('countered') && offerMigration.includes('accepted') && offerMigration.includes('expired'));
check('Offer mutation RPC is serialized, idempotent and role constrained', offerMigration.includes('FOR UPDATE') && offerMigration.includes('p_idempotency_key') && offerMigration.includes('Not a transaction participant'));
check('Offer API client exposes canonical negotiation operations', offerClient.includes('offers(leadId') && offerClient.includes('submitOffer') && offerClient.includes('respondToOffer'));

const failed = checks.filter(x => !x.ok);
for (const item of checks) console.log(`${item.ok ? 'PASS' : 'FAIL'} ${item.name}`);
console.log(`\nCustomer transaction lifecycle source audit: ${checks.length - failed.length}/${checks.length} PASS`);
if (failed.length) process.exit(1);
