import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const migrations = fs.readdirSync(path.join(root,'supabase/migrations')).filter(f=>/^\d{14}_.*\.sql$/.test(f)).sort();
const fail = (m)=>{ throw new Error(m); };
const latest = migrations[migrations.length-1] || '';
const sql = fs.readFileSync(path.join(root,'supabase/migrations',latest),'utf8');
if (!latest.startsWith('20261002190000_payment_gateway_customer_visibility_admin_control_360.sql')) fail('Payment gateway migration missing or not latest.');
if (!sql.includes('CREATE TABLE IF NOT EXISTS public.payment_gateway_methods')) fail('Canonical payment gateway table missing.');
if (!sql.includes("REVOKE ALL ON public.payment_gateway_methods FROM anon, authenticated")) fail('Direct customer table access is not revoked.');
if (!sql.includes("private.current_user_has_permission('settings','update')")) fail('Admin settings permission boundary missing.');
if (!sql.includes('CREATE OR REPLACE FUNCTION public.get_customer_payment_methods')) fail('Public payment-method discovery RPC missing.');
if (!sql.includes("is_enabled = true") || !sql.includes("customer_visible = true")) fail('Public RPC does not fail closed on disabled/hidden gateways.');
if (!sql.includes("GRANT EXECUTE ON FUNCTION public.get_customer_payment_methods(text) TO anon, authenticated")) fail('Public discovery RPC grant missing.');
if (!fs.existsSync(path.join(root,'src/lib/payment-gateways.ts'))) fail('Frontend payment gateway client missing.');
const lib = fs.readFileSync(path.join(root,'src/lib/payment-gateways.ts'),'utf8');
if (!lib.includes("rpc('get_customer_payment_methods'")) fail('Frontend is not using canonical payment-method RPC.');
const cart = fs.readFileSync(path.join(root,'src/pages/cart.tsx'),'utf8');
if (!cart.includes('CustomerPaymentMethods') || !cart.includes('context="checkout"')) fail('Checkout payment methods are not DB-driven.');
const portal = fs.readFileSync(path.join(root,'src/pages/portal.tsx'),'utf8');
if (!portal.includes('context="invoice"')) fail('Outstanding invoice payment methods are not visible.');
const admin = fs.readFileSync(path.join(root,'src/pages/admin/site-control.tsx'),'utf8');
if (!admin.includes("payment_gateway_methods")) fail('Admin payment gateway control is missing.');
if (!admin.includes('ADMIN CONTROLLED')) fail('Admin payment control boundary messaging missing.');
console.log(`Payment Gateway Customer Visibility 360: PASS (${migrations.length} migrations)`);
