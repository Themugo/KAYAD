import fs from 'node:fs';
import assert from 'node:assert/strict';

const read = (p) => fs.readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');
const navbar = read('src/components/Navbar.tsx');
const app = read('src/App.tsx');
const navLocation = read('src/utils/navLocation.ts');
const panel = read('src/components/layout/NotificationPanel.tsx');
const notificationsPage = read('src/pages/NotificationsPage.tsx');
const notificationDestination = read('src/utils/notificationDestination.ts');
const notificationCenter = read('src/components/NotificationCenter.tsx');
const commonNotificationCenter = read('src/components/features/common/NotificationCenter.tsx');
const chatApi = read('src/services/chatApi.ts');
const chatRoutes = read('backend/routes/chatRoutes.js');
const notificationRoutes = read('backend/routes/notificationRoutes.js');
const v1 = read('backend/routes/v1.js');
const server = read('backend/server.js');
const chatController = read('backend/controllers/chatController.js');
const notificationService = read('backend/services/notification.service.js');

assert.match(navbar, /onClick=\{\(\) => handleNavSelect\('chat'\)\}/, 'Navbar Messages utility must select canonical chat nav');
assert.match(navLocation, /chat:\s*'chat'/, 'chat nav must be preserved by URL canonicalizer');
assert.match(app, /activeNav === 'chat'[\s\S]*?<ChatView/, 'chat nav must render the existing ChatView');
assert.ok(app.includes("if (path === '/chat') return <RequireAuth><Navigate to=\"/?nav=chat\" replace /></RequireAuth>;"), '/chat deep link must converge on canonical chat nav behind auth');
assert.match(panel, /notificationDestination\(notif\)/, 'notification dropdown must use the canonical destination resolver');
assert.match(notificationsPage, /notificationDestination\(notification\)/, 'full notifications page must use the canonical destination resolver');
assert.match(notificationCenter, /notificationDestination\(n\)/, 'legacy notification center must use the canonical destination resolver');
assert.match(commonNotificationCenter, /notificationDestination\(n\)/, 'common notification center must use the canonical destination resolver');
assert.match(notificationDestination, /type === 'chat' \|\| type === 'message'\) return '\/?\?nav=chat'/, 'chat/message notifications must route to the communication hub before following stale links');
assert.match(notificationDestination, /link\.startsWith\('\/'\) && !link\.startsWith\('\/\/'\)/, 'stored links must be in-app paths, not protocol-relative external URLs');
assert.match(panel, /case 'message':[\s\S]*?case 'chat':/, 'chat notifications must use the message icon');
assert.match(chatApi, /request<T>\(path,/, 'chat API must use canonical HTTP transport');
assert.match(chatRoutes, /router\.get\("\/", protect/, 'chat inbox must be authenticated');
assert.match(chatRoutes, /router\.get\("\/:chatId\/messages", protect/, 'chat history must be authenticated');
assert.match(v1, /router\.use\("\/chat", chatRoutes\)/, 'versioned API must mount chat routes');
assert.match(server, /app\.use\("\/api\/chat", chatRoutes\)/, 'canonical unversioned API must mount chat routes');
assert.match(notificationRoutes, /router\.use\(protect\)/, 'notification endpoints must retain authentication');
assert.match(notificationService, /link, data/, 'notification service must persist canonical link and data');
assert.match(chatController, /metadata: \{ messageId: messageData\.id \}/, 'lead activity must reference the persisted message ID');
assert.match(chatController, /id: messageData\.id,\s*chatId,/, 'socket event must use persisted message ID');
assert.match(chatController, /link: "\/?\?nav=chat"/, 'new chat notifications must link to canonical chat nav');
assert.doesNotMatch(chatController, /\bmessageId\b(?!\s*:)/, 'no undefined messageId variable references should remain');
console.log('Chat / notification / navbar route convergence: PASS');
console.log('Auth guards and owner-scoped backend route mounting: PASS');
console.log('Message send/socket/notification ID contract: PASS');
