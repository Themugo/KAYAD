import fs from 'node:fs';
import assert from 'node:assert/strict';

const read = (path) => fs.readFileSync(path, 'utf8');
const security = read('backend/services/bidSecurityService.js');
const registration = read('backend/services/auctionRegistration.service.js');
const financial = read('backend/services/auctionFinancialIntegrity.service.js');
const bidController = read('backend/controllers/bidController.js');
const settlementRoutes = read('backend/routes/auctionSettlementRoutes.js');
const settlementService = read('backend/services/auctionSettlement.service.js');
const paymentCallback = read('backend/services/paymentCallback.service.js');
const api = read('src/api/api.exports.ts');
const page = read('src/pages/AuctionLivePage.jsx');
const activationTest = read('backend/tests/auction/bidSecurityPassActivation.test.js');

assert.match(security, /transaction\.type === "bid_commitment"[\s\S]*?finalizeCommitmentRegistration/);
assert.match(security, /transaction\.status === "success"[\s\S]*?finalizeCommitmentRegistration/);
assert.match(security, /holdType !== "high_value_deposit"[\s\S]*?registration commitment window has closed/);
assert.match(financial, /registration\.eligibility_status !== 'eligible'/);
assert.match(financial, /auctionStatus !== 'live'/);
assert.match(financial, /user\.phoneVerified !== true/);
assert.match(bidController, /status: \{ \$in: \["paid", "won", "lost"\] \}/);
assert.doesNotMatch(bidController.slice(bidController.indexOf('export const getAuctionBids'), bidController.indexOf('export const placeBid')), /"pending"/);
assert.match(settlementRoutes, /winner\?\.phoneVerified !== true/);
assert.match(settlementRoutes, /PROFILE_PHONE_MISMATCH/);
assert.match(settlementRoutes, /WINNER_PAYMENT_IN_PROGRESS/);
assert.match(settlementService, /atomicSettleAuctionWinnerPayment/);
assert.match(paymentCallback, /payment\.type === "auction_win"/);
assert.match(api, /securityPolicy: \(auctionId: string\)/);
assert.match(api, /initiateHighValueDeposit: \(auctionId: string\)/);
assert.match(page, /High-value bidder security/);
assert.match(page, /Complete the high-value security deposit/);
assert.match(page, /Winner payment status/);
assert.match(page, /setInterval\(refreshOutcome, 10000\)/);
assert.match(activationTest, /settles a commitment hold and then activates the eligible bidder registration/);
assert.match(activationTest, /does not activate a bidder whose required verification is missing/);
assert.match(activationTest, /does not activate the registration when the provider reports a failed payment/);
assert.match(security, /amountMismatch/);
assert.ok(security.includes('await update("auction_security_holds", mismatchedHoldId, { status: "failed" })'));
assert.ok(registration.includes('Boolean(user) && user?.isBanned !== true'));
assert.match(page, /Deposit required/);
console.log('PASS: security deposits, bidder-pass callback activation, confirmed bid history and winner payment handoff are connected to server-authoritative states');
