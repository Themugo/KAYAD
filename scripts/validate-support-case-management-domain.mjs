import fs from "node:fs";
import path from "node:path";
const root = process.cwd();
const read = f => fs.readFileSync(path.join(root, f), "utf8");
const exists = f => fs.existsSync(path.join(root, f));
const ctl = read("backend/controllers/supportController.js");
const routes = read("backend/routes/supportRoutes.js");
const svc = read("backend/services/support/supportCase.service.js");
const ser = read("backend/services/support/supportSerializers.js");
const mig = read("supabase/migrations/20261009150000_support_resolution_hardening.sql");
const checks = [
  ["canonical controller", ctl.includes("export const createTicket") && ctl.includes("export const staffUpdate")],
  ["single service writes through atomic RPCs", ["kayad_support_create_case", "kayad_support_append_message", "kayad_support_update_case", "kayad_support_rate_case"].every(n => svc.includes(n))],
  ["staff routes use PERM.MANAGE_SUPPORT, not adminOnly", routes.includes("requireSupportStaff") && !routes.includes("adminOnly")],
  ["customer projection is an allow-list without internal notes", ser.includes("m.isInternal !== true") && !ser.slice(ser.indexOf("export function customerDetail"), ser.indexOf("const staffPerson")).match(/assigned_to|escalated_to|closed_by|\bsla\b|priority/)],
  ["ticket number generated by the database", mig.includes("support_ticket_number_seq") && mig.includes("trg_support_ticket_number")],
  ["rpc functions are service_role only", mig.includes("FROM anon, authenticated") && mig.includes("TO service_role")],
  ["owner SELECT limited to safe columns (no messages)", mig.includes("GRANT SELECT (") && !/GRANT SELECT \([^)]*messages/.test(mig)],
  ["no direct customer writes", mig.includes("DROP POLICY IF EXISTS support_tickets_user_insert") && mig.includes("REVOKE ALL ON support_tickets FROM authenticated")],
  ["lifecycle + row_version concurrency", mig.includes("kayad_support_transition_allowed") && mig.includes("SUPPORT_VERSION_CONFLICT")],
  ["legacy admin facade delegates to the service", read("backend/routes/supportTicketAdminRoutes.js").includes("staffUpdate") && !exists("backend/controllers/supportTicketAdminController.js")],
  ["staff workspace mounted in AdminView", read("src/features/AdminView.tsx").includes("AdminSupportWorkspace")],
  ["orphan support pages removed", !exists("src/pages/Support.tsx") && !exists("src/pages/seller/SellerSupport.jsx") && !exists("src/pages/admin/AdminSupportTickets.jsx")],
];
let failed = 0;
for (const [name, ok] of checks) { console.log(`${ok ? "PASS" : "FAIL"} ${name}`); if (!ok) failed++; }
console.log(`Support case management gate: ${checks.length - failed}/${checks.length} PASS`);
process.exitCode = failed ? 1 : 0;
