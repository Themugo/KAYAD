import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const checks=[]; const check=(name,ok)=>{console.log(`${ok?'PASS':'FAIL'} ${name}`); if(!ok) checks.push(name)};
const route=read('backend/inspection/routes/inspectionRoutes.js');
const exec=read('backend/inspection/services/executionService.js');
const ctrl=read('backend/inspection/controllers/executionController.js');
const review=read('backend/inspectionBusinessCenter/services/reportReviewService.js');
const settle=read('backend/inspection/services/settlementService.js');
const mig=read('supabase/migrations/20261006150000_inspection_qa_report_versions.sql');
const booking=read('backend/inspection/services/bookingService.js');
check('canonical execution service exists', fs.existsSync(path.join(root,'backend/inspection/services/executionService.js')));
check('execution routes are mounted on canonical inspection router', route.includes("/execution/:bookingId/start") && route.includes("/execution/:bookingId/checklist") && route.includes("/execution/:bookingId/evidence") && route.includes("/execution/:bookingId/complete"));
check('inspector authorization is assignment-bound', exec.includes('assertInspectorAccess') && exec.includes('ensureExecution(booking, staff)'));
check('execution requires fully paid booking', exec.includes("payment_status !== 'fully_paid'"));
check('execution uses canonical vehicle_inspections', exec.includes("'vehicle_inspections'") && !exec.includes("db.findById('digital_inspections'"));
check('checklist is persisted canonically', exec.includes('checklist: normalized'));
check('evidence is hashed and persisted', exec.includes('sha256') && exec.includes('evidence.push(entry)'));
check('evidence uses existing secure upload pipeline', exec.includes('uploadEvidenceToStorage'));
check('completion requires checklist', exec.includes('checklist.length < 1'));
check('completion creates canonical report', exec.includes('reportService.createReport'));
check('QA queue resolves provider through bookings', review.includes("db.find('inspection_bookings'"));
check('QA delivery sends through canonical communications gateway', review.includes('sendUserCommunication'));
check('PDF generation is downstream of QA approval', read('backend/inspection/services/reportService.js').includes("status !== 'approved'"));
check('delivery requires approved report PDF', review.includes('version.status !== \'approved\'') && review.includes('!report.pdf_url'));
check('settlement requires buyer review', settle.includes("db.findOne('inspection_reviews'"));
check('payout requires buyer review', settle.includes("Settlement contains an inspection without a buyer review"));
check('booking can bind canonical vehicle', booking.includes('vehicle_id: bookingData.vehicleId'));
check('canonical execution evidence columns are migration-backed', mig.includes('ADD COLUMN IF NOT EXISTS evidence JSONB') && mig.includes('inspection_booking_id UUID'));
check('review atomically closes booking after review', mig.includes("UPDATE public.inspection_bookings SET status='customer_reviewed'") && mig.includes("UPDATE public.inspection_bookings SET status='closed'"));
console.log(`\nInspection execution E2E contract: ${checks.length?'FAIL':'PASS'}`);
if(checks.length) process.exit(1);
