import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd(), fail=[];
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const exists=f=>fs.existsSync(path.join(root,f));
const migration='20260914080000_102_theme_brand_governance_360.sql';
const migrations=fs.readdirSync(path.join(root,'supabase/migrations')).filter(f=>f.endsWith('.sql')).sort();
const versions=migrations.map(f=>f.match(/^(\d{14})_/)?.[1]);
if(!exists(`supabase/migrations/${migration}`)) fail.push('Operation 18 migration missing.');
if(new Set(versions).size!==versions.length) fail.push('Duplicate active migration timestamps detected.');
for(let i=1;i<versions.length;i++) if(versions[i-1]>=versions[i]) fail.push('Migration ordering is not strictly increasing.');
const sql=read(`supabase/migrations/${migration}`);
for(const t of ['theme_setting_versions','get_theme_brand_governance_360','save_theme_brand_version','rollback_theme_brand_version','private.current_user_has_permission','REVOKE ALL ON public.theme_setting_versions FROM PUBLIC, anon']) if(!sql.includes(t)) fail.push(`Migration missing required control: ${t}`);
const page=read('src/pages/admin/theme.tsx');
for(const t of ['Theme & Brand Governance','Theme Version History','Rollback','Save Theme Version','Change note','get_theme_brand_governance_360','save_theme_brand_version','rollback_theme_brand_version']) if(!page.includes(t)) fail.push(`UI missing required contract: ${t}`);
const applier=read('src/components/ThemeApplier.tsx');
for(const t of ['applyTheme','secondary_color','accent_color']) if(!applier.includes(t)) fail.push(`ThemeApplier missing governed token: ${t}`);
const engine=read('src/lib/theme-engine.ts');
for(const t of ['--theme-secondary','--theme-accent','--theme-heading-font','--theme-body-font','--theme-border-radius','--theme-spacing-scale']) if(!engine.includes(t)) fail.push(`Theme engine missing CSS token: ${t}`);
const css=read('src/index.css');
for(const t of ['--theme-secondary','--theme-accent','--theme-heading-font','--theme-body-font','--theme-border-radius','--theme-spacing-scale']) if(!css.includes(t)) fail.push(`CSS root token missing: ${t}`);
const manifest=read('supabase/MIGRATION_MANIFEST.md');
if(!manifest.includes(migration)) fail.push('Migration manifest missing Operation 18 migration.');
if(!manifest.includes(`contains ${migrations.length} uniquely timestamped active migrations`)) fail.push(`Migration manifest count is stale; expected ${migrations.length}.`);
const pkg=JSON.parse(read('package.json'));
if(!pkg.scripts?.['verify:operation-18-theme-brand-governance']) fail.push('Verifier not registered in package scripts.');
if(fail.length){console.error('Operation 18 Theme & Brand Governance 360 FAILED.'); fail.forEach(x=>console.error(`- ${x}`)); process.exit(1);}
console.log('Operation 18 Theme & Brand Governance 360: STRUCTURAL GATE PASSED');
console.log(`- Active migrations: ${migrations.length}`);
console.log(`- Latest migration: ${migrations.at(-1)}`);
console.log('- Governed theme RPC boundary: passed');
console.log('- Theme UI version history/rollback: passed');
console.log('- CSS token application boundary: passed');
console.log('- Manifest + package verifier registration: passed');
